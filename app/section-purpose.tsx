import styles from './section-purpose.module.css';

export function SectionPurpose({ kind }: { kind: 'care' | 'measurements' }) {
  const care = kind === 'care';
  return <aside className={styles.purpose} aria-label="Назначение раздела">
    <strong>{care ? 'Что нужно сделать дальше?' : 'Что измерили у пациента?'}</strong>
    <p>{care
      ? 'Здесь задачи со сроком и ответственным: повторный приём, обследование или контакт с пациентом. Врач утверждает план, сотрудник выполняет назначенные ему задачи.'
      : 'Здесь факты: давление, температура, рост и вес с датой и автором. Врач или медсестра с доступом записывает измерение; диагноз и лечение автоматически не меняются.'}</p>
    <span>{care
      ? 'Пример задачи: «Измерить давление через месяц». Само значение сохраняется в разделе «Измерения пациента».'
      : 'Пример измерения: «Сегодня давление 120/80». Когда измерить повторно и кто отвечает — задаётся в «Плане наблюдения».'}</span>
  </aside>;
}
